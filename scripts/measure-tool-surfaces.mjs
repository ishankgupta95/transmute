/**
 * Regenerates src/data/tool-surface-heights.ts — the measured initial heights
 * of every tool page's [data-tool-surface] region.
 *
 * Why this exists: tool UIs mount client-side (next/dynamic ssr:false), so the
 * surface is empty in the prerendered HTML. On desktop the band's flex chain
 * already gives the region its full height before the UI arrives, but below
 * lg it collapses to 0px and everything under it shifts down when the UI
 * mounts — a Lighthouse CLS of 0.397 on the live site (2026-08-31).
 * ToolPageLayout reserves each page's measured height up front so nothing
 * moves; this script is the source of those numbers.
 *
 * Run it against a mounted dev server whenever a tool's initial (no-file) UI
 * changes shape:
 *
 *   npm run dev            # in one terminal
 *   node scripts/measure-tool-surfaces.mjs   # rewrites the data module
 *
 * Widths: 412 is Lighthouse's mobile viewport (Moto G4); 768 is the md
 * breakpoint. lg is not recorded — the layout already sizes it pre-mount.
 */
import { chromium } from "playwright";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(path.join(root, "src/data/tools.ts"), "utf8");
const slugs = [...new Set([...src.matchAll(/slug:\s*"([a-z0-9-]+)"/g)].map((m) => m[1]))];

const VIEWPORTS = [
  { key: "sm", width: 412, height: 823 },
  { key: "md", width: 768, height: 900 },
];

const browser = await chromium.launch();
const results = {};
for (const vp of VIEWPORTS) {
  const ctx = await browser.newContext({ viewport: { width: vp.width, height: vp.height } });
  const page = await ctx.newPage();
  for (const slug of slugs) {
    await page.goto(`http://localhost:3000/${slug}`, { waitUntil: "domcontentloaded", timeout: 30000 });
    // Mounted = the surface has real height; the SSR wrapper alone has none.
    await page.waitForFunction(
      () => (document.querySelector("[data-tool-surface]")?.offsetHeight ?? 0) > 100,
      { timeout: 20000 },
    );
    await page.waitForTimeout(250);
    const h = await page.evaluate(() => document.querySelector("[data-tool-surface]").offsetHeight);
    (results[slug] ??= {})[vp.key] = h;
  }
  await ctx.close();
}
await browser.close();

const lines = slugs.map((s) => `  "${s}": { sm: ${results[s].sm}, md: ${results[s].md} },`);
const out = `/**
 * GENERATED by scripts/measure-tool-surfaces.mjs — do not edit by hand.
 *
 * Initial (no-file) height in px of each tool page's [data-tool-surface]
 * region, measured on a mounted page at 412px (sm — Lighthouse's mobile
 * viewport) and 768px (md). ToolPageLayout reserves this space before the
 * ssr:false tool UI mounts so the content below it never shifts (CLS).
 * Desktop needs no entry: the band's flex chain sizes the region pre-mount.
 *
 * Regenerate (dev server running): node scripts/measure-tool-surfaces.mjs
 */

export interface SurfaceHeights {
  sm: number;
  md: number;
}

/** Fallback for tools not yet measured: the most common archetype (DropZone). */
export const DEFAULT_SURFACE_HEIGHTS: SurfaceHeights = { sm: 428, md: 460 };

export const toolSurfaceHeights: Record<string, SurfaceHeights> = {
${lines.join("\n")}
};
`;
writeFileSync(path.join(root, "src/data/tool-surface-heights.ts"), out);
console.log(`wrote src/data/tool-surface-heights.ts (${slugs.length} tools)`);
